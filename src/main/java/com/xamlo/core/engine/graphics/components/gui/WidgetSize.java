package com.xamlo.core.engine.graphics.components.gui;

public class WidgetSize {
	
	protected int width;
	protected int height;
	
	public WidgetSize(int width, int height) {
		this.width = width;
		this.height = height;
	}
	
	public int getWidth() {
		return this.width;
	}
	
	public int getHeight() {
		return this.height;
	}
	

}
