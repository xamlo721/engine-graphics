package com.xamlo.core.engine.graphics.api.gui;

/**
 * UI-элемент, принимающий перетаскиваемые элементы. Диспетчер событий ввода
 * во время активного жеста следит за тем, лежит ли курсор над таргетом, и
 * вызывает у элемента {@link #setDropActive(boolean)} для подсветки состояния
 * «готов принять», а при отпускании кнопки — передаёт элемент слушателю
 * через onDrop (см. IDragListener).
 */
public interface IDropTarget {

	/** true, пока активный жест может быть сброшен на этот таргет (подсветка). */
	void setDropActive(boolean active);

	boolean isDropActive();

	/**
	 * Проверка типизированных данных активного жеста перед принятием (E4): диспетчер
	 * вызывает метод при попадании курсора на таргет во время перетаскивания и повторно
	 * при отпускании кнопки. false — таргет для этого payload'а «прозрачен»: подсветка
	 * не включается, onDragEnterTarget/onDrop не доставляются, жест завершается как сброс
	 * вне цели. По умолчанию принимает любой payload (историческое поведение), поэтому все
	 * существующие реализации компилируются без изменений; пользовательский контракт
	 * переопределяет метод под свой тип {@link DragPayload#getValue() значения}.
	 */
	default boolean acceptsDrag(DragPayload payload) {
		return true;
	}
}
