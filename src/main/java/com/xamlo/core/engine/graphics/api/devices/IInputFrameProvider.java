package com.xamlo.core.engine.graphics.api.devices;

/**
 * Канал передачи снимков {@link InputFrame} из потока LWJGL в диспетчерский
 * поток устройств. Контракт — один потребитель: вызовы takeNext() должны
 * выполняться только потоком-диспетчером, а публикация кадров — только
 * потоком рендера. Очередь внутри реализации ограничена по глубине, поэтому
 * остановка потребителя не приводит к росту памяти.
 */
public interface IInputFrameProvider {

	/**
	 * Возвращает следующий необработанный кадр или null, если новых кадров нет.
	 * Кадр выдаётся ровно одним вызовом повторно обработан быть не может.
	 */
	InputFrame takeNext();
}
