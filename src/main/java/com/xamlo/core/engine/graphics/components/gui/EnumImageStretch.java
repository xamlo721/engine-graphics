package com.xamlo.core.engine.graphics.components.gui;

/**
 * Режимы растяжения изображения внутри границ элемента. Все режимы учитываются
 * рендерером GUI-элементов при отрисовке фона ({@code UIElementRenderer}): FILL —
 * исторический путь единственного квада, остальные — набор до девяти квадов с
 * собственными UV без изменения шейдера (CPU-side nine-slice).
 */
public enum EnumImageStretch {

    FILL, // Растянуть изображение на всю область элемента (режим по умолчанию)

    FIT,  // Вписать внутрь, сохраняя пропорции и центрируя

    CENTER, // По центру без масштабирования (избыток обрезается границами элемента)

    NINEPATCH // Борды из NinePatchInsets не масштабируются, кромки/центр тянутся (см. ImageStretchLayout)

}
