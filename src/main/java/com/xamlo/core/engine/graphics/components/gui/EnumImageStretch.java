package com.xamlo.core.engine.graphics.components.gui;

/**
 * Режимы растяжения изображения внутри границ ImageView.
 * Текущий рендеринг поддерживает FILL (растяжение на всю область элемента);
 * FIT и CENTER зарезервированы под будущую работу с UV в шейдере.
 */
public enum EnumImageStretch {

    FILL, // Растянуть изображение на всю область элемента

    FIT,  // Вписать внутрь, сохраняя пропорции

    CENTER // По центру без масштабирования

}
