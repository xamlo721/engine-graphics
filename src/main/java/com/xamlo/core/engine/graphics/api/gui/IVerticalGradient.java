package com.xamlo.core.engine.graphics.api.gui;

/**
 * Маркерный контракт для элементов, рисующих вертикальный линейный двухцветный градиент между
 * верхней и нижней кромками собственных границ (см. {@code GradientRect}). Рендерер после фона
 * элемента отрисовывает набор горизонтальных полос с интерполяцией цвета ({@link #getTopColor()} вверху
 * — {@link #getBottomColor()} внизу), альфа-составляемым тем же путём, что и цвет фона.
 */
public interface IVerticalGradient {

    /** Цвет верхней кромки; null — градиент не рисуется. */
    IColor getTopColor();

    /** Цвет нижней кромки; null — градиент не рисуется. */
    IColor getBottomColor();

}
